def build_city_section(city, spots, prov):
    """生成一个城市的专册段"""
    L = ['## %s' % city, '']
    for name, typ, feat in spots:
        desc_tpl, dur, trans_tpl = SPOT_TYPES.get(typ, SPOT_TYPES['公园'])
        desc = desc_tpl.format(name=name, city=city, feat=feat)
        L.append('### %s' % name)
        L.append('')
        L.append(desc)
        L.append('')
        L.append('- **门票**：%s' % TICKET_TPL.get(typ, '以官方公布为准'))
        L.append('- **开放时间**：%s' % OPEN_TPL.get(typ, '以官方公告为准'))
        L.append('- **建议游玩**：%s' % dur)
        L.append('- **交通**：%s' % trans_tpl)
        L.append('- **实用建议**：%s' % TIPS_TPL.get(typ, '出行前查当日公告'))
        L.append('')
    return '\n'.join(L)


def gen_province(prov, city_spots):
    L = []
    L.append('# %s · 城市专册' % prov)
    L.append('')
    L.append('> 本文件把%s的景点下沉到**城市级**，每城给出可直接规划的景点条目。' % prov)
    L.append('> ')
    L.append('> **为什么有这一层**：原主攻略是省份粒度，景点集中在省会，')
    L.append('> 非省会城市常常只有一两个景点——在多目的地场景下，')
    L.append('> 「去这座城玩什么」没有可选空间，检索命中后也无从取舍。')
    L.append('> 本文件让每个城市都凑够能规划的景点数量。')
    L.append('> ')
    L.append('> **配套文件**：')
    L.append('> - 「%s—主攻略」讲全省气候、节奏与预算口径；' % prov)
    L.append('> - 「%s—城市总览」讲每城景点全表（主攻略原文下沉）；' % prov)
    L.append('> - 「%s—城际连接表」讲城际交通；' % prov)
    L.append('> - 「%s—跨城路线」讲逐日编排。' % prov)
    L.append('> ')
    L.append('> **数据口径**：景点名均为真实存在的景点；门票与开放时间给出常见区间，')
    L.append('> **统一以官方公布为准**，不提供精确价格，避免过期信息误导用户。')
    L.append('> 描述与建议属知识库补写的通用参考内容，用于补足原文未覆盖的城市。')
    L.append('')
    L.append('## 城市索引')
    L.append('')
    for city, spots in city_spots.items():
        L.append('- **%s**（%d 个景点）' % (city, len(spots)))
    L.append('')
    for city, spots in city_spots.items():
        L.append(build_city_section(city, spots, prov))
    return '\n'.join(L)


def main():
    os.makedirs(OUT, exist_ok=True)
    provs = sorted(set(MATERIAL.keys()) | {
        os.path.basename(f).split('—')[1]
        for f in glob.glob(os.path.join(KB, '*', '*主攻略*.md'))
    })
    done, empty = [], []
    for prov in provs:
        city_spots = MATERIAL.get(prov) or {}
        if not city_spots:
            empty.append(prov)
            continue
        content = gen_province(prov, city_spots)
        fname = '智慧旅游规划助手—%s—城市专册—%s—%s.md' % (prov, VERSION, DATE)
        io.open(os.path.join(OUT, fname), 'w', encoding='utf-8').write(content)
        done.append((prov, len(city_spots), sum(len(v) for v in city_spots.values())))

    print('=' * 66)
    print('城市专册生成完成')
    print('=' * 66)
    print('%-10s %8s %10s' % ('省份', '城市数', '景点数'))
    print('-' * 66)
    for p, c, s in done:
        print('%-10s %8d %10d' % (p, c, s))
    print('-' * 66)
    print('%-10s %8d %10d' % ('合计', sum(c for _, c, _ in done), sum(s for _, _, s in done)))
    print()
    print('已生成 %d 份' % len(done))
    if empty:
        print()
        print('⚠️ 素材表未覆盖的省（%d 个）: %s' % (len(empty), '、'.join(empty)))
        print('   → 这些省仍只有主攻略里的省会景点，需要补素材')


if __name__ == '__main__':
    main()
