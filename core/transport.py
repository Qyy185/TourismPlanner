def mode_key(value):
    """把界面传来的交通方式（键名或带图标/不带图标的文案）统一成内部键名。

    认不出来返回 ""，由 estimate_fare 回落到默认方式——
    宁可回到默认，也不要因为一个奇怪的值把整张卡算错。
    """
    s = str(value or "").strip()
    if not s:
        return ""
    if s in MODE_LABELS:
        return s
    for key, label in MODE_LABELS.items():
        if s == label or s == MODE_NAMES[key]:
            return key
    return ""


