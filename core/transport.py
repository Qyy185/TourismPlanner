def _is_suffix_noise(rest):
    """判断城市名被剥离后剩下的部分是否只是无实义的后缀噪声。

    「成都东」→ 残留「东」→ 噪声（还是成都）
    「五大连池」剥掉「大连」→ 残留「五池」→ 含实义字「五」→ 非噪声
    """
    if not rest:
        return True
    # 全是噪声字 → 视为同一城市
    return all(ch in _NOISE_CHARS for ch in rest)


def resolve_place(name):
    """把用户输入的出发地/目的地解析成标准城市。

    支持三种写法（按优先级）：
      1. 城市名或带后缀的城市名（「成都」「北京市」「成都东」）；
      2. 省级行政区名（「四川」「西藏」→ 取省会）；
      3. 城市别名包含关系（「去大理古城」→ 大理）。

    返回 (城市名, 省级行政区)；解析不出来返回 None。
    """
    q = re.sub(r"[\s·、,，。!！?？]+", "", str(name or ""))
    if not q:
        return None
    stripped = _SUFFIX_RE.sub("", q)

    # 0. 别名优先（景区名 → 行政名）：「雪乡」→ 双峰林场、「太阳岛」→ 哈尔滨。
    #    必须排在子串匹配之前，否则「太阳岛」会因「太阳」之类误撞，
    #    「雪乡」也匹配不到任何标准城市名。
    for alias, city in _PLACE_ALIAS.items():
        if alias in q or alias in stripped:
            return city, _CITY[city][2]

    # 1. 精确匹配城市
    for key in (q, stripped):
        if key in _CITY:
            lat, lon, prov = _CITY[key]
            return key, prov

    # 2. 城市名被包含（「成都东站」「去青海湖」）——长的优先，避免「东海」误撞「海」
    #    但必须排除「被包含后指向另一个城市」的情况：
    #    「五大连池」包含「大连」，若按子串直接取最长匹配会解析成「大连/辽宁」，
    #    实际它在黑龙江黑河市。判定：候选城市名出现在 q 里，
    #    且 q 不是以该城市名为主体的更长地名（用「该城市名前后是否还有实义字」判断）。
    candidates = [c for c in _CITY if len(c) >= 2 and (c in q or c in stripped)]
    if candidates:
        city = max(candidates, key=len)
        # 若原串里紧跟着城市名的后缀字（如「大连池」），说明这是另一个地名而非该城市
        rest = q.replace(city, "", 1)
        if rest and not _is_suffix_noise(rest):
            # 有实义残留：优先尝试更长的候选，否则判定为「不是该城市」
            longer = [c for c in candidates if len(c) > len(city) and c in q]
            if longer:
                city = max(longer, key=len)
            else:
                city = None
        if city:
            return city, _CITY[city][2]

    # 3. 省级行政区（含「四川省」这类写法）
    for prov in _PROVINCE_CAPITAL:
        if prov in q or prov in stripped:
            capital = _PROVINCE_CAPITAL[prov]
            return capital, prov

    return None


def _coord(city):
    lat, lon, prov = _CITY[city]
    return lat, lon, prov


def _haversine_km(a, b):
    """两点大圆距离（km）"""
    lat1, lon1 = a
    lat2, lon2 = b
    r = 6371.0
    p1, p2 = math.radians(lat1), math.radians(lat2)
    dp = p2 - p1
    dl = math.radians(lon2 - lon1)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(math.sqrt(min(1.0, h)))


