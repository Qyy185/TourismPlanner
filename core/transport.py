_SUFFIX_RE = re.compile(r"(市|省|自治区|特别行政区|地区|自治州|新区)$")

# 城市名后常见的「无实义」连接字：这些字跟在城市名后面时通常只是修饰词，
# 不构成另一个地名（如「大连池」里的「池」是「五大连池」的一部分）。
# 若残留里出现这些字之外的内容，说明原串指向的是另一个地名而非该城市。
_NOISE_CHARS = set("市省区县镇乡村站港口岸场园区县州东西南北新旧")

