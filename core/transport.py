def _hsr_price(rail_km):
    return max(_HSR_FLOOR, rail_km * _HSR_RATE)


def _slow_price(rail_km):
    return max(_SLOW_FLOOR, rail_km * _SLOW_RATE)


def _flight_price(air_km):
    """机票经济舱（含机建燃油）。返回 (低, 高)：低≈淡季折扣，高≈旺季全价。"""
    base = max(420.0, 220.0 + air_km * 0.62)
    return base * 0.70, base * 1.20


def _round5(x):
    return int(round(x / 5.0) * 5)


def _daily_ref(city):
    if city in _DAILY_HIGH_CITIES:
        return _DAILY_HIGH
    if city in _DAILY_RESORT_CITIES:
        return _DAILY_RESORT
    return _DAILY_BASE


def _int(v, default):
    try:
        return int(float(v))
    except (TypeError, ValueError):
        return default


