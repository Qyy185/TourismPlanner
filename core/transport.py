def estimate_fare(origin, destination, budget=None, days=3, people=1, mode=DEFAULT_MODE):
    """估算「出发地 → 目的地」的往返路费，并判断它是否装得进预算。

    mode：用户选的交通方式（"hsr" / "slow"，也接受界面文案）。**机票不可选**——
    航班价格波动太大，只展示区间作参考，不参与预算核算；用户传了 "air" 也会
    被回落到默认方式，避免出现「按一个随机折扣去扣预算」的荒唐结果。

    返回 dict：
      ok=False 时带 reason（例如缺少出发地、地名识别不出来）；
      ok=True 时包含：
        modes          全部可选方式 + 机票（都带 low/high/hours，供卡片全部展示）
        mode_options   其中**可勾选**的方式（高铁/普速；供界面生成单选项）
        mode/mode_name 本次实际用于核算的方式
        fare_low/high  所选方式的往返人均区间
        plan           预算判定（state = ok / tight / over / unknown）
    """
    days = max(1, _int(days, 3))
    people = max(1, _int(people, 1))

    o_raw = str(origin or "").strip()
    d_raw = str(destination or "").strip()
    if not o_raw or not d_raw:
        return {"ok": False, "reason": "missing"}

    o = resolve_place(o_raw)
    d = resolve_place(d_raw)
    if not o or not d:
        return {
            "ok": False,
            "reason": "unresolved",
            "origin": o[0] if o else o_raw,
            "dest": d[0] if d else d_raw,
        }

    o_city, o_prov = o
    d_city, d_prov = d

    if o_city == d_city:
        return {
            "ok": True,
            "same_city": True,
            "origin": o_city, "origin_prov": o_prov, "origin_input": o_raw,
            "dest": d_city, "dest_prov": d_prov, "dest_input": d_raw,
            "modes": [], "mode_options": [],
            "mode": "", "mode_name": "", "mode_fixed": True,
            "fare_low": 0, "fare_high": 0,
            "air_km": 0, "rail_km": 0,
            "special": [],
            "plan": _plan(0, budget, days, people, d_city),
        }

    air_km = _haversine_km(_coord(o_city)[:2], _coord(d_city)[:2])
    rail_km = air_km * _RAIL_FACTOR

    # 哪些方式可行：跨海 / 高原 / 两岸各有硬约束
    no_hsr = d_prov in {"海南", "西藏", "台湾"}
    only_air = d_prov in {"台湾"}
    too_short_for_flight = air_km < 420

    modes = []
    if not no_hsr:
        one = _hsr_price(rail_km)
        modes.append({
            "key": "hsr", "icon": "🚄", "name": "高铁二等座",
            "low": _round5(one * 2), "high": _round5(one * 2.12),
            "hours": round(rail_km / 250.0 + _HOURS_RAIL_OVERHEAD, 1),
        })
    if not only_air:
        one = _slow_price(rail_km)
        modes.append({
            "key": "slow", "icon": "🚂", "name": "普速硬卧",
            "low": _round5(one * 2 * 0.92), "high": _round5(one * 2 * 1.18),
            "hours": round(rail_km / 80.0 + _HOURS_RAIL_OVERHEAD, 1),
        })
    if not too_short_for_flight or only_air:
        lo, hi = _flight_price(air_km)
        modes.append({
            "key": "air", "icon": "✈️", "name": "机票经济舱",
            "low": _round5(lo * 2), "high": _round5(hi * 2),
            "hours": round(air_km / 700.0 + _HOURS_FLIGHT_OVERHEAD, 1),
        })

    # 展示顺序固定：高铁 → 普速 → 机票（不按价格排，否则三种方式的相对位置
    # 会随距离跳来跳去，用户点选时找不到北）
    _order = {"hsr": 0, "slow": 1, "air": 2}
    modes.sort(key=lambda m: _order.get(m["key"], 9))

    # 可选方式（不含机票）；机票只展示、不参与核算
    options = [m for m in modes if m["key"] in SELECTABLE_MODES]
    picked = mode_key(mode) or DEFAULT_MODE
    chosen = next((m for m in options if m["key"] == picked), None)
    if chosen is None:
        chosen = next((m for m in options if m["key"] == DEFAULT_MODE),
                      options[0] if options else None)
    mode_fixed = False      # True = 没得选（只能坐飞机），界面隐藏单选项
    if chosen is None:      # 例如台湾：只能乘飞机，那就按机票估算，但卡片会注明仅参考
        chosen = next((m for m in modes if m["key"] == "air"), None)
        mode_fixed = True
    if chosen is None:      # 理论上不会发生，兜个底
        chosen = {"key": "", "icon": "🚉", "name": "待定", "low": 0, "high": 0, "hours": 0}

    special = [msg for prov, msg in _SPECIAL.items() if prov == d_prov]

    return {
        "ok": True,
        "same_city": False,
        "origin": o_city, "origin_prov": o_prov, "origin_input": o_raw,
        "dest": d_city, "dest_prov": d_prov, "dest_input": d_raw,
        "air_km": int(round(air_km)), "rail_km": int(round(rail_km)),
        "modes": modes,
        "mode_options": options,
        "mode": chosen["key"], "mode_name": chosen["name"], "mode_fixed": mode_fixed,
        "fare_low": chosen["low"], "fare_high": chosen["high"],
        "special": special,
        "plan": _plan(chosen["low"], budget, days, people, d_city),
    }


def _plan(fare_low, budget, days, people, dest_city):
    """预算判定：路费能不能装进人均预算，扣完之后还剩多少。

      ok    预算充裕：扣掉路费后，剩下的够目的地按经济型标准玩
      tight 预算偏紧：路费装得下，但目的地部分要压缩
      over  预算不够：路费本身就把预算吃穿了，需单独列支
    """
    daily = _daily_ref(dest_city)
    need = daily * days                      # 目的地基础开销（人均）
    b = _int(budget, 0)
    if b <= 0:
        return {"state": "unknown", "budget": 0, "daily": daily, "need": need,
                "days": days, "people": people}
    rest = b - fare_low
    if rest >= need:
        state = "ok"
    elif rest >= 0:
        state = "tight"
    else:
        state = "over"
    return {
        "state": state,
        "budget": b,
        "daily": daily,
        "need": need,
        "days": days,
        "people": people,
        "rest": rest,                        # 人均：预算 − 路费
        "gap": max(0, need - rest),          # 人均还差多少才够基础开销
        "extra_total": max(0, -rest) * people,   # 需额外准备的总额（路费超预算时）
        "fare_share": (fare_low / float(b)) if b else 0.0,
    }


def fare_summary(info):
    """把估算结果压成一句话，供注入 Agent 提问（让模型预算口径一致）。

    必须写明「预算按哪种方式核算」——否则模型看到一个区间会自己挑一个数字，
    跟卡片上给用户的口径就对不上了。机票另注「仅供参照」，避免被当成核算依据。
    """
    if not info.get("ok"):
        return ""
    p = info.get("plan") or {}
    parts = ["出发地 %s → 目的地 %s（约 %d 公里）"
             % (info["origin"], info["dest"], info.get("air_km") or 0)]
    if info.get("same_city"):
        parts.append("出发地与目的地同城，往返路费按 0 计。")
        return "；".join(parts)

    chosen = info.get("mode")
    chosen_name = info.get("mode_name") or "待定"
    others = []
    for m in info.get("mode_options", []):
        if m["key"] != chosen:
            others.append("%s约 %d~%d 元/人" % (m["name"], m["low"], m["high"]))
    mode_txt = "往返路费按【%s】核算，约 %d~%d 元/人" % (
        chosen_name, info["fare_low"], info["fare_high"])
    if others:
        mode_txt += "（另一种可选方式：%s）" % "、".join(others)
    elif info.get("mode_fixed"):
        mode_txt = ("该目的地只能乘飞机，往返机票约 %d~%d 元/人（机票波动大，仅作参考）"
                    % (info["fare_low"], info["fare_high"]))
    parts.append(mode_txt)
    air = [m for m in info.get("modes", []) if m["key"] == "air"]
    if air and chosen != "air":
        parts.append("同期机票约 %d~%d 元/人，仅作参考（不可选，价格波动大）"
                     % (air[0]["low"], air[0]["high"]))
    if p.get("state") == "ok":
        parts.append("人均预算 %d 元，已包含往返路费，扣除后余 %d 元用于目的地 %d 天消费"
                     % (p["budget"], p["rest"], p["need"] // max(1, p["daily"])))
    elif p.get("state") == "tight":
        parts.append("人均预算 %d 元，扣除往返路费后仅余 %d 元用于目的地消费，需精打细算"
                     % (p["budget"], p["rest"]))
    elif p.get("state") == "over":
        parts.append("人均预算 %d 元不足以覆盖往返路费（差 %d 元/人），路费需单独列支"
                     % (p["budget"], -p["rest"]))
    return "；".join(parts) + "。"


