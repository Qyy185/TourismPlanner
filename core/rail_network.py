def transfer_hub(city):
    """景区级节点对应的最近高铁站（无则返回 None）"""
    return _TRANSFER_HUB.get(city)


def has_rail_reachable(city):
    """该城是否铁路可达：本身有站，或登记了接驳站"""
    return city in _LINE_INDEX or city in _TRANSFER_HUB


def rail_link(a, b):
    """判断两城之间的铁路连接情况。

    返回 dict：
      kind    'direct' 同干线直达 / 'transfer' 需换乘 / 'partial' 一端需公路接驳 /
              'none' 两端都无铁路
      line    直达时的干线名
      hops    换乘次数估计
      note    文字说明
    """
    if a == b:
        return {'kind': 'direct', 'line': '', 'hops': 0, 'note': '同城'}

    # 景区级节点先折算到其接驳站
    hub_a = _TRANSFER_HUB.get(a)
    hub_b = _TRANSFER_HUB.get(b)
    a_rail = hub_a or a
    b_rail = hub_b or b

    ina = a_rail in _LINE_INDEX
    inb = b_rail in _LINE_INDEX

    # 1. 同一条线 → 直达
    if ina and inb:
        for lname, ia, total in _LINE_INDEX[a_rail]:
            for lname2, ib, _t in _LINE_INDEX[b_rail]:
                if lname == lname2:
                    hops = abs(ia - ib)
                    if hubs := (hub_a or hub_b):
                        note = '%s 线上，%s 需公路接驳至%s站' % (lname, a if hub_a else b,
                                                              a_rail if hub_a else b_rail)
                    elif hops <= 1:
                        note = '%s 相邻站，班次密集' % lname
                    else:
                        note = '%s 线上，间隔 %d 站' % (lname, hops)
                    return {'kind': 'direct', 'line': lname, 'hops': 0, 'note': note}

    # 2. 两端都有站但不同线 → 需换乘
    if ina and inb:
        hubs = [s for s in ('北京', '石家庄', '郑州', '徐州', '南京', '合肥', '武汉',
                            '西安', '杭州', '南昌', '长沙', '贵阳', '成都', '重庆',
                            '兰州', '沈阳', '哈尔滨', '济南', '太原', '呼和浩特',
                            '齐齐哈尔', '牡丹江', '桂林', '南宁', '呼和浩特')
                if s in _LINE_INDEX and (s == a_rail or s == b_rail)]
        if hub_a or hub_b:
            note = '需公路接驳至最近车站，再经%s换乘' % ('、'.join(hubs[:2]) if hubs else '干线枢纽')
        else:
            note = '两地均有高铁站，需在枢纽换乘'
        return {'kind': 'transfer', 'line': '', 'hops': 1, 'note': note}

    # 3. 只有一端有铁路 → 公路接驳 + 铁路
    if ina or inb:
        other = b if ina else a
        note = '%s 无直达铁路，需先公路接驳至最近车站' % other
        return {'kind': 'partial', 'line': '', 'hops': 1, 'note': note}

    # 4. 两端都无 → 公路/航空
    return {'kind': 'none', 'line': '', 'hops': 0,
            'note': '两地均未登记铁路车站，以公路或航空为主'}
